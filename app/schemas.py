from typing import Any

from pydantic import BaseModel, Field


class ChatRequest(BaseModel):
    query: str = Field(..., description="User query on regulatory compliance or EPR obligations")
    stream: bool = Field(default=False, description="Whether to stream response tokens")
    model: str | None = Field(default=None, description="Optional override for model name")


class ChatUsage(BaseModel):
    prompt_tokens: int = Field(default=0, description="Tokens in the prompt")
    completion_tokens: int = Field(default=0, description="Tokens generated by model")
    total_tokens: int = Field(default=0, description="Total tokens used")
    cost_usd: float = Field(default=0.0, description="Estimated cost in USD")


class ChatResponse(BaseModel):
    status: str = Field(default="success", description="Status of the request")
    model_used: str = Field(..., description="Model that successfully answered")
    response: Any = Field(..., description="Structured response from the LLM")
    usage: ChatUsage = Field(..., description="Usage statistics for this call")


class UsageResponse(BaseModel):
    total_tokens: int = Field(default=0, description="Cumulative total tokens across all requests")
    prompt_tokens: int = Field(default=0, description="Cumulative prompt tokens")
    completion_tokens: int = Field(default=0, description="Cumulative completion tokens")
    cost_usd: float = Field(default=0.0, description="Cumulative estimated cost in USD")
    total_calls: int = Field(default=0, description="Total number of successful LLM calls")


class HealthResponse(BaseModel):
    status: str = Field(default="ok", description="Liveness check status")
    app: str = Field(default="ScrapLedger", description="Application name")
    environment: str = Field(default="local", description="Deployment environment")
